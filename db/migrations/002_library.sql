-- 5. LIBRARY FINES
-- ============================================================

CREATE TABLE IF NOT EXISTS public.library_fines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),

    school_id BIGINT NOT NULL,

    loan_id BIGINT NOT NULL,
    library_member_id BIGINT NOT NULL,

    fine_type VARCHAR(30) NOT NULL,

    amount NUMERIC(12,2) NOT NULL,
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0,

    issued_date DATE NOT NULL DEFAULT CURRENT_DATE,
    paid_date DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'OUTSTANDING',

    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    created_by BIGINT,
    updated_by BIGINT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_library_fines_public_id
        UNIQUE (public_id),

    CONSTRAINT chk_library_fines_amount
        CHECK (amount > 0),

    CONSTRAINT chk_library_fines_amount_paid
        CHECK (
            amount_paid >= 0
            AND amount_paid <= amount
        ),

    CONSTRAINT chk_library_fines_dates
        CHECK (
            paid_date IS NULL
            OR paid_date >= issued_date
        ),

    CONSTRAINT chk_library_fines_type
        CHECK (
            fine_type IN (
                'OVERDUE',
                'LOST_BOOK',
                'DAMAGED_BOOK',
                'OTHER'
            )
        ),

    CONSTRAINT chk_library_fines_status
        CHECK (
            status IN (
                'OUTSTANDING',
                'PARTIALLY_PAID',
                'PAID',
                'WAIVED'
            )
        ),

    CONSTRAINT fk_library_fines_school
        FOREIGN KEY (school_id)
        REFERENCES public.schools(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_fines_loan
        FOREIGN KEY (loan_id)
        REFERENCES public.library_loans(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_fines_member
        FOREIGN KEY (library_member_id)
        REFERENCES public.library_members(id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_library_fines_school_id
    ON public.library_fines(school_id);

CREATE INDEX IF NOT EXISTS idx_library_fines_loan_id
    ON public.library_fines(loan_id);

CREATE INDEX IF NOT EXISTS idx_library_fines_member_id
    ON public.library_fines(library_member_id);

CREATE INDEX IF NOT EXISTS idx_library_fines_status
    ON public.library_fines(status);


