-- 4. LIBRARY LOANS
-- ============================================================

CREATE TABLE IF NOT EXISTS public.library_loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),

    school_id BIGINT NOT NULL,

    book_copy_id BIGINT NOT NULL,
    library_member_id BIGINT NOT NULL,

    loan_date DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date DATE NOT NULL,

    returned_date DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'BORROWED',

    renewal_count INTEGER NOT NULL DEFAULT 0,

    issued_by BIGINT,
    returned_to BIGINT,

    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    created_by BIGINT,
    updated_by BIGINT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_library_loans_public_id
        UNIQUE (public_id),

    CONSTRAINT chk_library_loans_dates
        CHECK (
            due_date >= loan_date
            AND (
                returned_date IS NULL
                OR returned_date >= loan_date
            )
        ),

    CONSTRAINT chk_library_loans_renewal_count
        CHECK (renewal_count >= 0),

    CONSTRAINT chk_library_loans_status
        CHECK (
            status IN (
                'BORROWED',
                'RETURNED',
                'OVERDUE',
                'LOST',
                'CANCELLED'
            )
        ),

    CONSTRAINT chk_library_loans_status_dates
        CHECK (
            (
                status = 'RETURNED'
                AND returned_date IS NOT NULL
            )
            OR
            (
                status IN ('BORROWED', 'OVERDUE', 'LOST')
                AND returned_date IS NULL
            )
            OR
            (
                status = 'CANCELLED'
                AND returned_date IS NULL
            )
        ),

    CONSTRAINT fk_library_loans_school
        FOREIGN KEY (school_id)
        REFERENCES public.schools(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_loans_book_copy
        FOREIGN KEY (book_copy_id)
        REFERENCES public.book_copies(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_loans_member
        FOREIGN KEY (library_member_id)
        REFERENCES public.library_members(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_loans_issued_by
        FOREIGN KEY (issued_by)
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_library_loans_returned_to
        FOREIGN KEY (returned_to)
        REFERENCES public.users(id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_library_loans_school_id
    ON public.library_loans(school_id);

CREATE INDEX IF NOT EXISTS idx_library_loans_book_copy_id
    ON public.library_loans(book_copy_id);

CREATE INDEX IF NOT EXISTS idx_library_loans_member_id
    ON public.library_loans(library_member_id);

CREATE INDEX IF NOT EXISTS idx_library_loans_status
    ON public.library_loans(status);

CREATE INDEX IF NOT EXISTS idx_library_loans_due_date
    ON public.library_loans(due_date);

-- Only one active loan may exist for a copy.
CREATE UNIQUE INDEX IF NOT EXISTS uq_library_loans_active_copy
    ON public.library_loans(book_copy_id)
    WHERE is_active = TRUE
      AND returned_date IS NULL
      AND status IN (
          'BORROWED',
          'OVERDUE',
          'LOST'
      );


