-- ============================================================
-- 3. VALIDATE MEMBER IDENTITY
-- ============================================================
-- Ensures the selected learner/employee/guardian actually
-- belongs to the supplied user and school.

CREATE OR REPLACE FUNCTION public.validate_library_member_identity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    IF NEW.membership_type = 'LEARNER' THEN

        IF NOT EXISTS (
            SELECT 1
            FROM public.learners l
            WHERE l.id = NEW.learner_id
              AND l.user_id = NEW.user_id
              AND l.school_id = NEW.school_id
        ) THEN
            RAISE EXCEPTION
                'Library learner membership is inconsistent with user or school';
        END IF;

    ELSIF NEW.membership_type = 'EMPLOYEE' THEN

        IF NOT EXISTS (
            SELECT 1
            FROM public.employees e
            WHERE e.id = NEW.employee_id
              AND e.user_id = NEW.user_id
              AND e.school_id = NEW.school_id
        ) THEN
            RAISE EXCEPTION
                'Library employee membership is inconsistent with user or school';
        END IF;

    ELSIF NEW.membership_type = 'GUARDIAN' THEN

        IF NOT EXISTS (
            SELECT 1
            FROM public.guardians g
            WHERE g.id = NEW.guardian_id
              AND g.user_id = NEW.user_id
        ) THEN
            RAISE EXCEPTION
                'Library guardian membership is inconsistent with user';
        END IF;

    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_library_member_identity
ON public.library_members;

CREATE TRIGGER trg_validate_library_member_identity
BEFORE INSERT OR UPDATE OF
    user_id,
    school_id,
    learner_id,
    employee_id,
    guardian_id,
    membership_type
ON public.library_members
FOR EACH ROW
EXECUTE FUNCTION public.validate_library_member_identity();


